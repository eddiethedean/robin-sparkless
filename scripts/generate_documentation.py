"""Generate release-scoped documentation inventories; use --check in CI."""
from __future__ import annotations

import argparse
import inspect
import json
from pathlib import Path
import subprocess
import tomllib

ROOT = Path(__file__).resolve().parents[1]


def save(path: str, text: str, check: bool) -> None:
    target = ROOT / path
    if check:
        if not target.exists() or target.read_text() != text:
            raise SystemExit(f"Generated documentation is stale: {path}; run scripts/generate_documentation.py")
    else:
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(text)


def compatibility(check: bool) -> None:
    version = tomllib.loads((ROOT / 'python/pyproject.toml').read_text())['project']['version']
    files = subprocess.check_output(['git', 'ls-files'], cwd=ROOT, text=True).splitlines()
    groups = {
        'Pytest expected-output files (mixed historical oracle provenance)': 'tests/expected_outputs/',
        'Separate generated plan/input JSON fixtures': 'tests/fixtures/',
        'Pytest parity source modules': 'tests/parity/',
        'Connect test source/fixture files': 'tests/connect/',
    }
    lines = [f'# Compatibility evidence — {version}', '',
             'Generated by `scripts/generate_documentation.py` from tracked source; CI checks for drift.', '',
             'These are inventory counts, **not pass counts or a percentage of PySpark parity**.',
             'See the [support contract](SUPPORT_MATRIX.md) for explicit per-surface support states.', '',
             '| Corpus | Tracked files |', '| --- | ---: |']
    for label, prefix in groups.items():
        suffix = '.json' if 'JSON' in label or 'expected-output' in label else '.py'
        count = sum(p.startswith(prefix) and p.endswith(suffix) for p in files)
        lines.append(f'| {label} | {count} |')
    lines += ['', '## Oracle provenance and scope', '',
              '- The expected-output loader defaults to historical PySpark **3.2** fixtures. Inspect each fixture; that default is not Spark4 certification.',
              '- Live dual-backend examples run against pinned **PySpark 3.5.8** and **4.0.5** in docs CI, with session/import identity assertions.',
              '- The Connect protocol/client corpus is pinned to **4.0.5**. Its plan/type subset is smaller than the local Python API.',
              '- Compatibility profiles (`3.5` / `4.0`) adjust behavior; they do not select or install a real oracle.',
              '- Current run pass/fail results belong to their exact commit. Use [release evidence](RELEASE_EVIDENCE.md), not fixture counts, to establish what ran.', '',
              '## Coverage states', '',
              '| State | Interpretation |', '| --- | --- |',
              '| Behavior-tested | An executable regression/example exists for the named context; see support matrix links |',
              '| Implemented | A public implementation exists; combinations outside linked tests remain workload-dependent |',
              '| Stub/no-op | Compatibility spelling without distributed/runtime guarantees; see differences |',
              '| Unsupported | Explicitly outside the surface contract |',
              '| Unknown | No reviewed evidence for that API/context combination |', '',
              'A successful CI suite does not prove equivalence of every operation, type, error, or dataset.',
              'For adoption, run your own transformation with explicit schemas, null/empty/invalid inputs,',
              'ordering rules, storage round trips and your exact production Spark version.', '',
              'See [test creation](TEST_CREATION_GUIDE.md), [differences](PYSPARK_DIFFERENCES.md),',
              'and [Connect support](SPARK_CONNECT.md).', '']
    save('docs/PARITY_STATUS.md', '\n'.join(lines), check)


def api(check: bool) -> None:
    import sparkless
    from sparkless.sql import functions, types
    from sparkless.sql.window import Window
    from sparkless import server, external_catalog

    sections = []
    for name in ['SparkSession', 'DataFrame', 'Column', 'GroupedData', 'DataFrameReader', 'DataFrameWriter']:
        sections.append((name, getattr(sparkless, name)))
    session = sparkless.SparkSession.builder.app_name('documentation-inventory').get_or_create()
    try:
        sections += [('SessionBuilder', type(sparkless.SparkSession.builder)),
                     ('Catalog', type(session.catalog)), ('RuntimeConfig', session.conf),
                     ('LocalRDD', type(session.range(0).rdd)),
                     ('CancellationHandle', type(session.cancellation_handle()))]
    finally:
        session.stop()
    sections += [('Window', Window), ('functions', functions), ('types', types),
                 ('server', server), ('external_catalog', external_catalog)]
    lines = [f'# Python symbol reference — {sparkless.__version__}', '',
             'Generated from the installed package by `scripts/generate_documentation.py --api`.',
             'CI regenerates this against its wheel and fails on drift. This is the runtime',
             'symbol/signature inventory; [API contracts](PYTHON_API_REFERENCE.md) supplies',
             'argument semantics, returns, errors and practical examples for common operations.',
             'Missing native docstrings are stated explicitly; importability alone is not',
             'evidence of Spark parity. Consult the [support contract](SUPPORT_MATRIX.md).', '']
    inventory = {}
    for label, obj in sections:
        lines += [f'## {label}', '']
        names = getattr(obj, '__all__', None)
        if names is None:
            names = [n for n in dir(obj) if not n.startswith('_')]
        entries = {}
        for name in sorted(set(names)):
            if name.startswith('_'):
                continue
            value = getattr(obj, name, None)
            if inspect.ismodule(value):
                continue
            # Avoid documenting imported typing/helpers as package API.
            if inspect.ismodule(obj) and not getattr(obj, '__all__', None):
                module = getattr(value, '__module__', '')
                if not module.startswith(('sparkless', 'builtins')) or not callable(value):
                    continue
            if callable(value):
                try:
                    signature = str(inspect.signature(value))
                except (ValueError, TypeError):
                    signature = '(native signature unavailable)'
                doc = inspect.getdoc(value) or 'No runtime docstring. See the API contracts and support matrix before relying on this symbol.'
                # Object-address reprs are unstable and not useful API documentation.
                import re
                signature = re.sub(r' at 0x[0-9a-fA-F]+', '', signature)
                lines += [f'### `{name}{signature}`', '', doc, '']
                entries[name] = signature
            else:
                lines += [f'### `{name}`', '', 'Property/descriptor; see the API contracts for semantics.', '']
                entries[name] = 'property'
        inventory[label] = entries
    save('docs/PYTHON_API_SYMBOLS.md', '\n'.join(lines), check)
    save('docs/reference/python-api-inventory.json', json.dumps(inventory, indent=2, sort_keys=True)+'\n', check)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--api', action='store_true', help='also inspect installed Sparkless public symbols')
    args = parser.parse_args()
    compatibility(args.check)
    if args.api:
        api(args.check)


if __name__ == '__main__':
    main()
